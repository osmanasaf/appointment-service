CREATE TABLE IF NOT EXISTS plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    code VARCHAR(30) NOT NULL UNIQUE,
    max_employees INT NOT NULL,
    max_appointments_monthly INT NOT NULL,
    max_services INT NOT NULL,
    max_branches INT NOT NULL,
    features TEXT NOT NULL,
    monthly_price DECIMAL(10, 2) NOT NULL,
    yearly_price DECIMAL(10, 2) NOT NULL
);

CREATE TABLE IF NOT EXISTS business_subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    business_id BIGINT NOT NULL UNIQUE,
    plan_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    trial_end_date DATE,
    current_period_start DATE NOT NULL,
    current_period_end DATE NOT NULL,
    manual BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_business_subscriptions_plan FOREIGN KEY (plan_id) REFERENCES plans(id)
);

CREATE TABLE IF NOT EXISTS plan_limit_usages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    business_id BIGINT NOT NULL,
    usage_year INT NOT NULL,
    usage_month INT NOT NULL,
    appointments_count INT NOT NULL DEFAULT 0,
    sms_sent INT NOT NULL DEFAULT 0,
    whatsapp_sent INT NOT NULL DEFAULT 0,
    CONSTRAINT uq_plan_limit_usage_business_period UNIQUE (business_id, usage_year, usage_month)
);

CREATE INDEX IF NOT EXISTS idx_business_subscriptions_business_id ON business_subscriptions (business_id);
CREATE INDEX IF NOT EXISTS idx_plan_limit_usages_business_period ON plan_limit_usages (business_id, usage_year, usage_month);

